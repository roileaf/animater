// Native, open PF2e bestiary actions only. Read a copy of each LevelDB so a
// running Foundry keeps its locks. No paid-module content or rules prose ships.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire}from'node:module';
import {fileURLToPath}from'node:url';
import {findNpcAbility,abilityForm,breathElement,breathShape}from'../scripts/catalogs/pf2e/npc-abilities.mjs';
import {reviewedNpcAction}from'../scripts/catalogs/pf2e/npc-reviewed-actions.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const arg=(key,fallback)=>{const i=process.argv.indexOf(key);return i<0?fallback:process.argv[i+1];};
const data=arg('--data',path.resolve(root,'../..')),app=arg('--foundry','C:/Program Files/Foundry Virtual Tabletop/resources/app');
const require=createRequire(path.join(app,'main.js')),{ClassicLevel}=require('classic-level');
const manifest=JSON.parse(fs.readFileSync(path.join(data,'systems/pf2e/system.json'),'utf8'));
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'animater-npc-index-')),groups=new Map();let occurrences=0;
try{
 for(const pack of manifest.packs.filter(p=>p.type==='Actor')){
  const copy=path.join(temp,pack.name);fs.cpSync(path.join(data,'systems/pf2e',pack.path),copy,{recursive:true,filter:file=>path.basename(file)!=='LOCK'});
  const db=new ClassicLevel(copy,{valueEncoding:'json'});
  try{
   await db.open();const actors=new Map(),items=[];
   for await(const[key,value]of db.iterator()){
    if(key.startsWith('!actors!'))actors.set(value._id,value);
    else if(key.startsWith('!actors.items!'))items.push([key.split('!')[2].split('.')[0],value]);
   }
   for(const[actorId,item]of items){
    const actor=actors.get(actorId);if(actor?.type!=='npc'||item.type!=='action'||item.system?.actionType?.value==='passive')continue;
    const event={type:'use',systemId:'pf2e',actor,item:{...item,actor}},named=findNpcAbility(event),inferred=named??abilityForm(event);
    const form=inferred?{id:inferred.id,aim:inferred.aim,trigger:inferred.trigger,...(inferred.variant?{variant:inferred.variant}:{})}:null;
    if(form?.id==='breath')form.variant=`${breathElement(item)}-${breathShape(item)}`;
    const traits=item.system?.traits?.value??[],actionType=item.system?.actionType?.value??'action',actions=item.system?.actions?.value??null;
    const key=JSON.stringify([item.name,form,traits,actionType,actions]);
    let entry=groups.get(key);
    if(!entry){entry={id:`action-${pack.name}-${actorId}-${item._id}`,name:item.name,names:[item.name],creatures:[],sources:[],traits,actionType,actions,form,coverage:named?'shared':form?'inferred':'unmapped'};groups.set(key,entry);}
    if(!entry.creatures.includes(actor.name))entry.creatures.push(actor.name);
    entry.sources.push(`Compendium.pf2e.${pack.name}.Actor.${actorId}.Item.${item._id}`);occurrences++;
   }
  }finally{await db.close();}
 }
 const entries=[...groups.values()].sort((a,b)=>a.name.localeCompare(b.name)||a.id.localeCompare(b.id));
 // Apply explicit choices after grouping so source IDs and existing per-action
 // exclusions stay stable as newly reviewed designs are added.
 for(const entry of entries){const review=reviewedNpcAction(entry.id);if(!review)continue;
  const {rationale,...form}=review;entry.form=form;entry.coverage='reviewed';entry.rationale=rationale;
 }
 const source={system:'pf2e',version:manifest.version,packs:'Native Actor packs',occurrences,total:entries.length,uniqueNames:new Set(entries.map(a=>a.name)).size,animated:entries.filter(a=>a.form).length,reviewed:entries.filter(a=>a.coverage==='reviewed').length};
 fs.writeFileSync(path.join(root,'data/pf2e-npc-actions.mjs'),`// Generated by tools/build-pf2e-npc-actions.mjs. Factual names, source links and animation metadata; no rules prose.\nexport const PF2E_NPC_ACTION_SOURCE = ${JSON.stringify(source)};\nexport const PF2E_NPC_ACTIONS = ${JSON.stringify(entries)};\n`);
 console.log(JSON.stringify(source,null,2));
}finally{
 if(!path.resolve(temp).startsWith(path.resolve(os.tmpdir())+path.sep+'animater-npc-index-'))throw Error('Unsafe temporary path');
 fs.rmSync(temp,{recursive:true,force:true});
}
