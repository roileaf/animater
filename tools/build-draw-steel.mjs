// Draw Steel library source: hero abilities from the installed `draw-steel` system's Abilities
// compendium, written to data/draw-steel-catalog.mjs (committed). Each row holds the facts the
// adapter reads from a live ability (scripts/systems/draw-steel.mjs abilityRow), so the catalog and
// a used ability take the same look. Monster abilities are not listed: they play the fallbacks by
// their keywords, distance and damage. Conditions are CONFIG entries (ds.CONFIG.conditions): the
// tool only checks their ids still exist in the system bundle.
//
//   node tools/build-draw-steel.mjs [--system=<path>] [--foundry=<app path>]
//
// Reads the installed pack offline through Foundry's own classic-level module, from a temp copy so a
// running world's LOCK is never touched.
import { cpSync, existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { abilityRow, DS_CONDITIONS } from "../scripts/systems/draw-steel.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const OUTPUT = join(ROOT, "data", "draw-steel-catalog.mjs");
const DEFAULT_SYSTEM = resolve(ROOT, "..", "..", "systems", "draw-steel");
const DEFAULT_FOUNDRY = process.platform === "win32" ? "C:/Program Files/Foundry Virtual Tabletop/resources/app" : "/opt/foundryvtt/resources/app";
export const PACK = Object.freeze({ name: "abilities", path: "packs/abilities", type: "ability" });

export async function readPack(systemDir, foundryApp) {
  const require = createRequire(join(foundryApp, "package.json"));
  const { ClassicLevel } = require("classic-level");
  const copy = mkdtempSync(join(tmpdir(), "animater-draw-steel-"));
  try {
    // File by file: a running world holds LOCK (and may hold LOG) open; the data files copy fine.
    for (const name of readdirSync(join(systemDir, PACK.path))) {
      if (name === "LOCK") continue;
      try { cpSync(join(systemDir, PACK.path, name), join(copy, name)); } catch (error) { if (/\.(?:ldb|log)$|^CURRENT$|^MANIFEST/.test(name) && !/^LOG/.test(name)) throw error; }
    }
    const db = new ClassicLevel(copy, { valueEncoding: "json" }), items = [], folders = new Map();
    for await (const [key, value] of db.iterator()) {
      if (key.startsWith("!items!") && value?.type === PACK.type) items.push(value);
      else if (key.startsWith("!folders!")) folders.set(value._id, value);
    }
    await db.close();
    return { items, folders };
  } finally {
    rmSync(copy, { recursive: true, force: true });
  }
}

// The top folder an ability sits in: its class, Kits, Common Abilities…
export function topFolder(folderId, folders) {
  let folder = folders.get(folderId), seen = 0;
  while (folder?.folder && folders.has(folder.folder) && seen++ < 10) folder = folders.get(folder.folder);
  return folder?.name ?? null;
}
export function abilityEntryRow(doc, folders = new Map()) {
  const row = abilityRow(doc);
  return { id: doc._id, name: doc.name, img: doc.img ?? null, dsid: doc.system?._dsid ?? null, group: topFolder(doc.folder, folders),
    keywords: row.keywords, type: row.type, category: row.category, distance: row.distance, target: row.target,
    damageTypes: row.damageTypes, damages: row.damages, conditions: row.conditions, rolled: row.rolled, heals: row.heals,
    forced: row.forced, resource: row.resource, verbs: row.verbs };
}
export function validateRows(rows) {
  const problems = [], ids = new Set();
  for (const r of rows) {
    if (!r.id || ids.has(r.id)) problems.push(`${r.name}: missing or duplicate id ${r.id}`);
    ids.add(r.id);
    if (!r.name) problems.push(`${r.id}: no name`);
    if (!r.distance) problems.push(`${r.name}: no distance type`);
  }
  return problems;
}
// The condition ids the system bundle defines (ds.CONFIG.conditions: `  bleeding: {` keys).
export function conditionIdsFrom(bundle) {
  const start = bundle.indexOf("const conditions = {");
  if (start < 0) return [];
  const block = bundle.slice(start, bundle.indexOf("\n};", start));
  return [...block.matchAll(/^ {2}([a-z]+): \{/gm)].map((m) => m[1]);
}
const renderModule = ({ source, abilities }) => `// Generated by tools/build-draw-steel.mjs from the draw-steel system's compendium. Do not edit by hand.
export const DRAW_STEEL_SOURCE = ${JSON.stringify(source)};
export const DRAW_STEEL_ABILITIES = [
${abilities.map((a) => JSON.stringify(a)).join(",\n")}
];
`;

export async function build({ systemDir = DEFAULT_SYSTEM, foundryApp = DEFAULT_FOUNDRY, output = OUTPUT } = {}) {
  const version = JSON.parse(readFileSync(join(systemDir, "system.json"), "utf8")).version;
  const { items, folders } = await readPack(systemDir, foundryApp);
  const abilities = items.map((doc) => abilityEntryRow(doc, folders)).sort((a, b) => a.name.localeCompare(b.name) || a.id.localeCompare(b.id));
  const problems = validateRows(abilities);
  if (problems.length) throw Error(`Draw Steel library rows are invalid:\n${problems.join("\n")}`);
  const bundle = join(systemDir, "draw-steel.mjs");
  const found = existsSync(bundle) ? conditionIdsFrom(readFileSync(bundle, "utf8")) : null;
  const missing = found ? DS_CONDITIONS.filter((id) => !found.includes(id)) : [];
  if (missing.length) throw Error(`Draw Steel conditions missing from draw-steel.mjs: ${missing.join(", ")}`);
  const source = { systemId: "draw-steel", version, reader: "leveldb", repository: "MetaMorphic-Digital/draw-steel", packs: { ability: PACK.name },
    counts: { ability: abilities.length }, conditions: [...DS_CONDITIONS], conditionsVerified: Boolean(found) };
  writeFileSync(output, renderModule({ source, abilities }));
  return source;
}

if (import.meta.url === pathToFileURL(resolve(process.argv[1] ?? "")).href) {
  const arg = (name) => process.argv.find((a) => a.startsWith(`--${name}=`))?.split("=").slice(1).join("=");
  try {
    console.log(JSON.stringify(await build({ systemDir: arg("system") ?? DEFAULT_SYSTEM, foundryApp: arg("foundry") ?? process.env.FOUNDRY_APP ?? DEFAULT_FOUNDRY })));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
