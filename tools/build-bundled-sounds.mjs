// Lists every sound Animater ships (assets/sounds) for the media library, by folder, as
// data/bundled-sounds.mjs. Run after adding or removing bundled sounds: node tools/build-bundled-sounds.mjs
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const base = path.join(root, "assets", "sounds");
const AUDIO = /\.(?:ogg|mp3|wav|flac|m4a|webm)$/i;
const dirs = {};
async function walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) await walk(full);
    else if (AUDIO.test(entry.name)) (dirs[path.relative(base, dir).split(path.sep).join("/")] ??= []).push(entry.name);
  }
}
await walk(base);
const sorted = Object.fromEntries(Object.keys(dirs).sort().map((d) => [d, dirs[d].sort((a, b) => a.localeCompare(b, "en", { numeric: true }))]));
const count = Object.values(sorted).reduce((n, files) => n + files.length, 0);
await writeFile(path.join(root, "data", "bundled-sounds.mjs"),
  `// Generated by tools/build-bundled-sounds.mjs: every sound under assets/sounds, by folder (${count} files).\n` +
  `export const BUNDLED_SOUND_DIRS = ${JSON.stringify(sorted)};\n`);
console.log(`${count} bundled sounds in ${Object.keys(sorted).length} folders`);
